#!/usr/bin/env python3
"""The game's art for the FM-1, from the Isle of Bears assets: the isles, the bears and the cards as RGB565 sprites,
and the QR code of the rules.

    python3 tools/gen_art.py      -> app/art.h (committed; run again when the art changes)

The assets are HEYBYE GAMING's, in the game's own repository: IOB_ASSETS (default ../isle-of-bears/assets).
The QR code needs segno (pip install segno).

Pixels are stored byte-swapped, as fm1-base's canvas keeps them (the panel takes RGB565 big-endian), so a sprite is
copied without converting. KEY marks a transparent pixel. Edges are blended over the colour each sprite is drawn on
(the sea for the isles, the ice for the bears), then cut at half alpha: a clean outline with no halo.
"""
import os
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parents[1]
ASSETS = Path(os.environ.get("IOB_ASSETS", HERE.parent / "isle-of-bears" / "assets"))
OUT = HERE / "app" / "art.h"
RULES_URL = "https://isle-of-bears.heybyedesign.com/rules-en.pdf"
ISLE = 80                 # an isle: 2 x 2 cells of 40
BEAR_H = 30               # a bear's height on its cell
SEA = (36, 110, 170)      # the deep sea between the isles
ICE = (200, 232, 248)     # what a bear stands on (the isles' light blue)
KEY = 0x0821              # never produced by the art (checked)
CARD_W = 76               # a card in your hand (app.c CARD_W)
CARD_ICON_L = (30, 22)    # its icon's box; the computer's row has the small one
CARD_ICON_S = (16, 12)
ARTS = ["straight", "straight_1", "diagonal", "diagonal_1", "leap", "swap", "party", "push", "dismiss", "banish",
        "playtwice", "discard", "wild"]   # iob.h's art order
ISLES = ["taiwan", "bali", "srilanka", "england"]   # board order: top-left, top-right, bottom-left, bottom-right


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def swap(v):
    return ((v >> 8) & 0xFF) | ((v & 0xFF) << 8)


def sprite(im, under):
    im = im.convert("RGBA")
    w, h = im.size
    out = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a < 128:
                out.append(swap(KEY))
                continue
            k = a / 255
            c = rgb565(*(round(v * k + u * (1 - k)) for v, u in zip((r, g, b), under)))
            if c == KEY:
                c ^= 0x0020
            out.append(swap(c))
    return w, h, out


def emit(name, w, h, px, lines):
    lines.append(f"static const uint16_t {name}_px[{w * h}] = {{")
    for i in range(0, len(px), 16):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in px[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const spr_t {name} = {{{w}, {h}, {name}_px}};")


def main():
    lines = ["/* generated by fm1/tools/gen_art.py from assets/ (HEYBYE GAMING's art): do not edit */",
             "#pragma once", "#include <stdint.h>",
             "typedef struct { uint16_t w, h; const uint16_t *px; } spr_t;   /* byte-swapped RGB565 */",
             f"#define SPR_KEY 0x{swap(KEY):04X}u   /* a transparent pixel, as stored */",
             f"#define ART_SEA RGB({SEA[0]}, {SEA[1]}, {SEA[2]})",
             f"#define ART_ICE RGB({ICE[0]}, {ICE[1]}, {ICE[2]})", ""]
    total = 0
    for k, n in enumerate(ISLES):
        im = Image.open(ASSETS / "isles" / f"isle-{n}.png").resize((ISLE, ISLE), Image.LANCZOS)
        w, h, px = sprite(im, SEA)
        emit(f"ISLE_{k}", w, h, px, lines)
        total += w * h * 2
    names = []
    for c in ("white", "black"):
        for i in range(1, 9):
            im = Image.open(ASSETS / "pieces" / f"{c}-bear-{i:02d}.png")
            bbox = im.getchannel("A").getbbox()
            im = im.crop(bbox)
            w = max(1, round(im.width * BEAR_H / im.height))
            if w > 36:                         # the lying-down ones: as wide as a cell allows
                w = 36
            im = im.resize((w, round(im.height * w / im.width) if w == 36 else BEAR_H), Image.LANCZOS)
            w, h, px = sprite(im, ICE)
            nm = f"BEAR_{c[0].upper()}{i}"
            emit(nm, w, h, px, lines)
            names.append(nm)
            total += w * h * 2
    # the cards: each art's middle icon (the face without its wavy edges), big for your hand and small for the
    # computer's row, blended over the card's own colour (orange: black's cards, sky blue: white's); and the wavy edge
    cards = {}
    for o, own in enumerate(("white", "black")):
        for a, art in enumerate(ARTS):
            im = Image.open(ASSETS / "cards" / f"{own}-{art}.png").convert("RGBA")
            bg = im.getpixel((5, im.height // 2))[:3]
            mid = im.crop((0, 60, im.width, im.height - 60))
            px = mid.load()
            box = [mid.width, mid.height, 0, 0]
            for y in range(mid.height):
                for x in range(mid.width):
                    r, g, b, al = px[x, y]
                    if al > 128 and abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2]) > 90:
                        box = [min(box[0], x), min(box[1], y), max(box[2], x + 1), max(box[3], y + 1)]
            icon = mid.crop(tuple(box))
            for size, (bw, bh) in (("L", CARD_ICON_L), ("S", CARD_ICON_S)):
                k = min(bw / icon.width, bh / icon.height)
                im2 = icon.resize((max(1, round(icon.width * k)), max(1, round(icon.height * k))), Image.LANCZOS)
                w, h, px2 = sprite(im2, bg)
                nm = f"CARD_{size}_{o}_{a}"
                emit(nm, w, h, px2, lines)
                total += w * h * 2
            cards[o] = bg
        im = Image.open(ASSETS / "cards" / f"{own}-{ARTS[0]}.png").convert("RGBA")
        for edge, crop in (("TOP", (0, 0, im.width, 44)), ("BOT", (0, im.height - 44, im.width, im.height))):
            w, h, px2 = sprite(im.crop(crop).resize((CARD_W, 5), Image.LANCZOS), cards[o])
            emit(f"CARD_{edge}_{o}", w, h, px2, lines)
            total += w * h * 2
    for o in (0, 1):
        r, g, b = cards[o]
        lines.append(f"#define ART_CARD_{o} RGB({r}, {g}, {b})")
    for size in ("L", "S"):
        lines.append(f"static const spr_t *const CARD_{size}[2][{len(ARTS)}] = {{" + ", ".join(
            "{" + ", ".join(f"&CARD_{size}_{o}_{a}" for a in range(len(ARTS))) + "}" for o in (0, 1)) + "};")
    lines.append("static const spr_t *const CARD_EDGE[2][2] = {{&CARD_TOP_0, &CARD_BOT_0}, {&CARD_TOP_1, &CARD_BOT_1}};")
    lines.append("static const spr_t *const ISLES[4] = {&ISLE_0, &ISLE_1, &ISLE_2, &ISLE_3};")
    lines.append("static const spr_t *const BEARS[16] = {" + ", ".join("&" + n for n in names) + "};")
    import segno                         # the rules' QR code: a row of bits each, the leftmost module the top bit
    q = segno.make(RULES_URL, error="m", boost_error=False)
    rows = [row for row in q.matrix]
    n = len(rows)
    lines.append(f"/* {RULES_URL} */")
    lines.append(f"#define QR_N {n}")
    lines.append(f"static const uint64_t QR_ROWS[{n}] = {{")
    for row in rows:
        v = 0
        for b in row:
            v = v << 1 | (1 if b else 0)
        lines.append(f"    0x{v:016X}ull,")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"art: {OUT.name} ({total} bytes of pixels, QR {n} x {n})")


if __name__ == "__main__":
    main()
